-- Persistent contact enrichment for a Network Map country registry project.
-- Mirrors the Argentina - Registry tables (official_registry_contact_emails and
-- official_registry_contact_email_evidence) so the Directory reads every country
-- the same way. Rows are keyed to official_registry_providers.source_record_id
-- WITHOUT a foreign key, because the registry refresh truncates and reloads
-- official_registry_providers. Original provider rows are never updated.
--
-- Additions over Argentina (all additive, nothing renamed):
--   * facility_name_snapshot / postal_code_snapshot so contacts can be re-keyed if
--     a refresh ever changes source_record_id.
--   * 'exact_registry_code' match basis (country-neutral form of exact_refes_code).
--   * official_registry_contact_points(+_evidence) for websites, phones, fax and
--     contact forms, in the same shape as the email tables.
--   * enriched_contacts column appended to the view.

CREATE TABLE IF NOT EXISTS official_registry_contact_emails (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_record_id text NOT NULL CHECK (length(btrim(source_record_id)) > 0),
  email text NOT NULL CHECK (length(email) >= 5 AND length(email) <= 320
    AND position('@' in email) > 1 AND position(' ' in email) = 0),
  normalized_email text,
  purposes text[] NOT NULL DEFAULT ARRAY['general'],
  source_status text NOT NULL CHECK (source_status IN
    ('official_published', 'historical_published', 'candidate_unreviewed')),
  match_basis text NOT NULL CHECK (match_basis IN
    ('exact_facility_name_and_address', 'exact_refes_code', 'exact_registry_code',
     'official_explicit_facility', 'website_facility_match', 'manual_review')),
  delivery_verified boolean NOT NULL DEFAULT false,
  first_discovered_at timestamptz NOT NULL DEFAULT now(),
  last_source_checked_at timestamptz,
  notes text,
  facility_name_snapshot text,
  postal_code_snapshot text,
  CONSTRAINT official_registry_contact_emails_unique UNIQUE (source_record_id, normalized_email)
);
CREATE INDEX IF NOT EXISTS official_registry_contact_emails_record_idx
  ON official_registry_contact_emails (source_record_id, source_status);

CREATE TABLE IF NOT EXISTS official_registry_contact_email_evidence (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contact_email_id bigint NOT NULL REFERENCES official_registry_contact_emails(id) ON DELETE CASCADE,
  source_url text NOT NULL CHECK (source_url ~ '^https?://'),
  source_title text,
  documented_purpose text,
  page_published_at date,
  observed_at timestamptz NOT NULL DEFAULT now(),
  evidence_note text,
  CONSTRAINT official_registry_contact_email_evidence_unique UNIQUE (contact_email_id, source_url)
);

CREATE TABLE IF NOT EXISTS official_registry_contact_points (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_record_id text NOT NULL CHECK (length(btrim(source_record_id)) > 0),
  channel_type text NOT NULL CHECK (channel_type IN ('website', 'phone', 'fax', 'contact_form', 'whatsapp')),
  value text NOT NULL CHECK (length(btrim(value)) > 0),
  normalized_value text,
  purposes text[] NOT NULL DEFAULT ARRAY['general'],
  source_status text NOT NULL CHECK (source_status IN
    ('official_published', 'historical_published', 'candidate_unreviewed')),
  match_basis text NOT NULL CHECK (match_basis IN
    ('exact_facility_name_and_address', 'exact_refes_code', 'exact_registry_code',
     'official_explicit_facility', 'website_facility_match', 'manual_review')),
  first_discovered_at timestamptz NOT NULL DEFAULT now(),
  last_source_checked_at timestamptz,
  notes text,
  facility_name_snapshot text,
  postal_code_snapshot text,
  CONSTRAINT official_registry_contact_points_unique UNIQUE (source_record_id, channel_type, normalized_value)
);
CREATE INDEX IF NOT EXISTS official_registry_contact_points_record_idx
  ON official_registry_contact_points (source_record_id, source_status);

CREATE TABLE IF NOT EXISTS official_registry_contact_point_evidence (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contact_point_id bigint NOT NULL REFERENCES official_registry_contact_points(id) ON DELETE CASCADE,
  source_url text NOT NULL CHECK (source_url ~ '^https?://'),
  source_title text,
  documented_purpose text,
  page_published_at date,
  observed_at timestamptz NOT NULL DEFAULT now(),
  evidence_note text,
  CONSTRAINT official_registry_contact_point_evidence_unique UNIQUE (contact_point_id, source_url)
);

CREATE OR REPLACE VIEW official_registry_providers_with_contacts AS
SELECT p.source_record_id, p.source_url, p.name, p.normalized_name, p.address_line1,
  p.formatted_address, p.city, p.state_region, p.postal_code, p.country_code, p.lat, p.lng,
  p.phone, p.website, p.email, p.primary_provider_type, p.capability_tags, p.quality_score,
  p.master_key, p.synced_at,
  COALESCE((SELECT jsonb_agg(jsonb_build_object('email', c.email, 'purposes', c.purposes,
      'source_status', c.source_status, 'delivery_verified', c.delivery_verified,
      'last_source_checked_at', c.last_source_checked_at,
      'sources', COALESCE((SELECT jsonb_agg(jsonb_build_object('url', e.source_url,
          'title', e.source_title, 'purpose', e.documented_purpose,
          'page_published_at', e.page_published_at) ORDER BY e.source_url)
        FROM official_registry_contact_email_evidence e WHERE e.contact_email_id = c.id), '[]'::jsonb))
      ORDER BY c.email)
    FROM official_registry_contact_emails c
    WHERE c.source_record_id = p.source_record_id
      AND c.source_status IN ('official_published', 'historical_published')), '[]'::jsonb) AS enriched_emails,
  COALESCE((SELECT jsonb_agg(jsonb_build_object('type', c.channel_type, 'value', c.value,
      'purposes', c.purposes, 'source_status', c.source_status,
      'last_source_checked_at', c.last_source_checked_at,
      'sources', COALESCE((SELECT jsonb_agg(jsonb_build_object('url', e.source_url,
          'title', e.source_title, 'purpose', e.documented_purpose,
          'page_published_at', e.page_published_at) ORDER BY e.source_url)
        FROM official_registry_contact_point_evidence e WHERE e.contact_point_id = c.id), '[]'::jsonb))
      ORDER BY c.channel_type, c.value)
    FROM official_registry_contact_points c
    WHERE c.source_record_id = p.source_record_id
      AND c.source_status IN ('official_published', 'historical_published')), '[]'::jsonb) AS enriched_contacts
FROM official_registry_providers p;
